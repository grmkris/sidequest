import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const build = await Bun.build({
  entrypoints: [new URL('apps/explore/src/commons-app/main.tsx', root).pathname],
  target: 'browser',
  format: 'iife',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
})
if (!build.success || build.outputs.length !== 1)
  throw new Error('Commons App bundle failed: ' + build.logs.map((log) => log.message).join('\n'))
// Bundled SDK diagnostics are displayed to clients too; normalize their copy before computing the CSP hash.
const script = (await build.outputs[0].text()).replaceAll(' — ', ': ').replaceAll('</script', '<\\/script')
const digest = createHash('sha256').update(script).digest('base64')
const style = [
  readFileSync(new URL('../packages/react/src/commons-ui/styles.css', import.meta.url), 'utf8'),
  readFileSync(new URL('../apps/explore/src/commons-app/styles.css', import.meta.url), 'utf8'),
].join('\n')
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${digest}'; style-src 'unsafe-inline'; connect-src 'none'; frame-src 'none'; img-src 'none'; base-uri 'none'; form-action 'none'"><title>Sidequest Commons</title><style>${style}</style></head><body><div id="root"></div><script>${script}</script></body></html>`
if (Buffer.byteLength(html) > 1024 * 1024) throw new Error('Commons App exceeds 1 MiB')
const generated = `// Generated by bun scripts/gen-commons-app.mjs. Breaking changes require ui://sidequest/commons/v2.html.\nexport const commonsHtml = ${JSON.stringify(html)}\n`
const output = new URL('apps/api/src/generated/commons-app.ts', root)
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated)
    throw new Error('Run bun scripts/gen-commons-app.mjs; Commons App is stale')
} else writeFileSync(output, generated)
