/**
 * Copies the ABIs the SDK needs from Foundry's build output into typed `as const` modules, so viem infers
 * every call and event. Run after `forge build` whenever a contract's interface changes:
 *
 *   bun scripts/gen-abi.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const out = join(root, 'contracts/out')
const target = join(root, 'packages/sdk/src/abi')

/** The Sidequest v1 entries (ADR-0011) come from the implementations in `contracts/src/sidequest/`. */
const contracts: Array<[file: string, name: string, module: string, exportName: string]> = [
  ['ERC8183WithAuthorization.sol', 'ERC8183WithAuthorization', 'core', 'coreAbi'],
  ['IERC8004.sol', 'IERC8004Identity', 'identity', 'identityAbi'],
  ['SidequestHolding.sol', 'SidequestHolding', 'sidequestHolding', 'sidequestHoldingAbi'],
  ['SidequestEvaluator.sol', 'SidequestEvaluator', 'sidequestEvaluator', 'sidequestEvaluatorAbi'],
  ['StakeVault.sol', 'StakeVault', 'stakeVault', 'stakeVaultAbi'],
  ['FeeSchedule.sol', 'FeeSchedule', 'feeSchedule', 'feeScheduleAbi'],
  // SIDE is an existing token (testnet's Factory v2, mainnet's nad.fun clone); both are OpenZeppelin ERC-20s with
  // permit. The test token mirrors that interface and carries OZ's ERC-20 and permit errors for revert decoding.
  ['LaunchToken.sol', 'LaunchToken', 'sideToken', 'sideTokenAbi'],
  ['TestnetFaucet.sol', 'TestnetFaucet', 'testnetFaucet', 'testnetFaucetAbi'],
]

const index: string[] = []
for (const [file, name, module, exportName] of contracts) {
  // Registry wallet consent is an external interface, already verified in the retained ERC-8004 ABI.
  // Keep the SDK subset generated from that source; no deployed Sidequest interface changes.
  const registryMethods = new Set([
    'register',
    'ownerOf',
    'getAgentWallet',
    'isAuthorizedOrOwner',
    'setMetadata',
    'getMetadata',
    'setAgentWallet',
    'unsetAgentWallet',
    'setAgentURI',
    'tokenURI',
    'Registered',
    'URIUpdated',
    'MetadataSet',
  ])
  const artifact =
    module === 'identity'
      ? {
          abi: (
            JSON.parse(readFileSync(join(root, 'contracts/abi/erc8004/IdentityRegistry.json'), 'utf8')) as Array<{
              name?: string
            }>
          ).filter((item) => registryMethods.has(item.name ?? '')),
        }
      : (JSON.parse(readFileSync(join(out, file, `${name}.json`), 'utf8')) as { abi: Array<{ type?: string }> })
  // A test token's constructor is no part of the interface the SDK calls.
  if (module === 'sideToken') artifact.abi = artifact.abi.filter((item) => item.type !== 'constructor')
  const source =
    module === 'identity' ? 'contracts/abi/erc8004/IdentityRegistry.json' : `contracts/out/${file}/${name}.json`
  const body = JSON.stringify(artifact.abi, null, 2)
  // oxlint.config.ts caps files at 500 lines; only an ABI that long gets the directive, so none goes unused.
  const long = body.split('\n').length > 500
  writeFileSync(
    join(target, `${module}.ts`),
    `// Generated by scripts/gen-abi.ts from ${source}. Do not edit.\n` +
      (long ? `/* oxlint-disable max-lines -- a generated ABI is as long as its contract's interface */\n` : '') +
      `export const ${exportName} = ${body} as const\n`,
  )
  index.push(`export { ${exportName} } from './${module}.ts'`)
}
writeFileSync(join(target, 'index.ts'), `${index.join('\n')}\n`)
console.log(`wrote ${contracts.length} ABIs to packages/sdk/src/abi`)
